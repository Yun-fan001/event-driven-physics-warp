def add_section(doc, title, items):
    doc.add_heading(title, level=1)
    for item in items:
        if isinstance(item, tuple):
            p = doc.add_paragraph()
            r = p.add_run(item[0] + "：")
            r.bold = True
            p.add_run(item[1])
        else:
            doc.add_paragraph(item, style="List Bullet")


